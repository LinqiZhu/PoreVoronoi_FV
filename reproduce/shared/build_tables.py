def manufactured(summary):
    path = REV / "table_03" / "manufactured_stokes.csv"
    if not path.exists():
        return None
    df = pd.read_csv(path)
    record = {}
    for functional, block in df.groupby("load_functional"):
        block = block.sort_values("sites_per_side")
        entry = {
            "levels": block["level_label"].tolist(),
            "voxels_per_side": block["voxels_per_side"].tolist(),
            "sites_per_side": block["sites_per_side"].tolist(),
            "N_cv": block["N_cv"].tolist(),
            "N_system": block["N_system"].tolist(),
            "nnz_A": block["nnz_A"].tolist(),
            "nnz_D": block["nnz_D"].tolist(),
            "e_u_percent": block["e_u_percent"].tolist(),
            "e_p_percent": block["e_p_percent"].tolist(),
            "e_phi_percent": block["e_phi_percent"].tolist(),
            "mass_backward_error_dimensionless":
                block["mass_backward_error_dimensionless"].tolist(),
        }
        inverse_H = 1.0 / block["H_over_L"].values
        for metric in ["e_u_percent", "e_p_percent", "e_phi_percent"]:
            for name, count in (("all_levels", None), ("last_three", 3)):
                a, r2 = slope(inverse_H, block[metric].values, count)
                entry["%s__slope__%s" % (metric, name)] = {"slope": -a, "r_squared": r2}
        record[functional] = entry
    summary["manufactured_stokes"] = record
    return df


