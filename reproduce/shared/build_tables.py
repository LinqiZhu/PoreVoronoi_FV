def fmt(value, digits=2, dash="--"):
    if value is None or (isinstance(value, float) and not math.isfinite(value)):
        return dash
    return ("%%.%df" % digits) % value


STATUS_DISPLAY = {
    "converged": "converged",
    "not_converged": "not converged",
    "non_positive_velocity_diagonal": "\\(A\\) diagonal not positive",
    "non_positive_schur_diagonal": "Schur diagonal not positive",
}


def status_text(value):
    return STATUS_DISPLAY.get(str(value), str(value).replace("_", " "))


def sci(value, digits=2):
    if value is None or (isinstance(value, float) and not math.isfinite(value)):
        return "--"
    exponent = int(math.floor(math.log10(abs(value)))) if value else 0
    mantissa = value / (10.0 ** exponent)
    return "\\(%.*f\\times10^{%d}\\)" % (digits, mantissa, exponent)


def slope(x, y, last=None):
    x = np.log(np.asarray(x, dtype=float))
    y = np.log(np.asarray(y, dtype=float))
    if last:
        x, y = x[-last:], y[-last:]
    coefficients = np.polyfit(x, y, 1)
    residual = np.corrcoef(x, y)[0, 1] ** 2 if len(x) > 2 else float("nan")
    return float(coefficients[0]), float(residual)


def ladder_frame(root=None):
    """Assemble the refinement ladder from the per-run records.

    The driver writes its summary CSV only when the whole sweep finishes, so a
    partially finished sweep leaves a stale CSV on disk.  The per-run `row.json`
    files are written as each level completes and are therefore the authoritative
    source; reading them removes the possibility of building a table from an
    older summary.
    """
    root = Path(root or (REV / "figure_06/refinement" / "runs"))
    records = []
    for path in sorted(root.glob("*/*/row.json")):
        records.append(json.loads(path.read_text(encoding="utf-8")))
    if not records:
        return None
    frame = pd.DataFrame(records)
    order = ["orthogonal_duct", "skewed_duct", "bentheimer_crop"]
    frame["_case_order"] = frame["case"].map(
        {name: index for index, name in enumerate(order)}
    ).fillna(len(order))
    return frame.sort_values(["_case_order", "level_index"]).drop(columns="_case_order")


