def canonical(summary):
    """Generate the headline cells from a CSV, and signs from K/K_ref in the run records."""
    path = PROJECT / "data/controlled_cases/expected/table_source_values.csv"
    df = pd.read_csv(path)
    names = {"thin_wall": "Thin-wall case", "narrow_throat": "Narrow-throat case", "maze": "Maze case"}
    records = []
    lines = [r"\begin{table}[t]", r"\centering",
             r"\caption{Same-flow verification of the shared-trace Stokes branch. The reference flow generates both the trajectory sites and the comparison field; these are not independent forward-validation cases. The permeability column is the signed discrepancy \(e_K^{\rm s}\), whereas the flux and cell-mean columns are non-negative relative discrepancies.}",
             r"\label{tab:final-accuracy-cost}", r"\begingroup", r"\scriptsize",
             r"\setlength{\tabcolsep}{3.2pt}", r"\resizebox{\textwidth}{!}{%",
             r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
             r"Case & \(N_c\) & \(e_K^{\rm s}\) (\%) & \(e_\phi\) (\%) & \(e_{u,\mathrm{cell}}^{\mathrm{solve}}\) (\%) & \(r_\infty^m\) \\", r"\midrule"]
    for _, row in df.iterrows():
        case = row["case"]
        manifest = PROJECT / "data/controlled_cases" / (case + "/run_record.json")
        m = json.loads(manifest.read_text(encoding="utf-8"))["row"]
        signed = 100 * (m["K_eff_x"] - m["K_ref_x"]) / abs(m["K_ref_x"])
        if not math.isclose(abs(signed), row["e_K_percent"], abs_tol=1e-10):
            raise ValueError(f"CSV/manifest disagreement: {case}")
        lines.append("%s & %d & %.2f & %.2f & %.2f & %s \\\\" % (
            names.get(case, CASE_DISPLAY.get(case, case)), int(row["N_c"]), signed,
            row["e_phi_percent"], row["e_u_percent"], sci(row["mass_inf_per_volume"])))
        records.append({"case":case, "e_K_signed_percent":signed,
                        "e_phi_percent":float(row["e_phi_percent"]), "e_u_percent":float(row["e_u_percent"]),
                        "K":m["K_eff_x"], "K_ref":m["K_ref_x"],
                        "manifest":manifest.relative_to(PROJECT).as_posix()})
    lines += [r"\bottomrule", r"\end{tabular}%", "}", r"\endgroup", r"\end{table}"]
    (GEN/"final_accuracy_cost_table.tex").write_text(HEADER % path.relative_to(PROJECT).as_posix() + "\n".join(lines) + "\n", encoding="utf-8")
    summary["canonical_same_flow"] = records
    return df

