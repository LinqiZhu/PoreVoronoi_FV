def controlled_refinement(summary):
    df = ladder_frame()
    if df is None:
        return None
    path = REV / "figure_06/refinement" / "runs"
    signed = pd.read_csv(REV / "supplementary/s2_discretization" / "permeability_readouts.csv")
    signed = signed[signed["K_method_flux"].notna()].copy()
    signed["e_K_signed_percent"] = 100 * (signed["K_method_flux"] - signed["K_reference_stored"]) / signed["K_reference_stored"].abs()
    df = df.merge(signed[["case", "N_cv", "e_K_signed_percent"]], on=["case", "N_cv"], validate="one_to_one")
    if len(df) != 18:
        raise ValueError("Incomplete controlled-refinement signed join")
    df.to_csv(REV / "figure_06/refinement" / "mask_fps_refinement_from_runs.csv", index=False)
    lines = [
        "\\begin{table}[t]", "\\centering",
        "\\caption{Controlled prescribed-site refinement on fixed voxel masks. "
        "Sites come from deterministic graph farthest-point sampling over every "
        "pore voxel; the mask, reference field, boundary convention, viscosity, "
        "forcing, trace basis, stabilization and solver are identical across all "
        "levels of a case. \\(H_g/h\\) is the graph fill distance in pore-graph "
        "edges and \\(q_S/h\\) the minimum site separation. \\(e_p\\) is omitted "
        "for the orthogonal duct, whose exact pressure perturbation is constant "
        "so that the metric has a round-off denominator. The permeability column reports the signed discrepancy \\(e_K^{\\rm s}\\). A dagger marks the two Bentheimer entries smaller than the 0.868 percent readout offset; these are unresolved as accuracy statements.}",
        "\\label{tab:controlled-refinement}", "\\begingroup", "\\scriptsize",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{@{}llrrrrrrrr@{}}", "\\toprule",
        "Case & Level & \\(N_c\\) & KKT dim & \\(H_g/h\\) & \\(q_S/h\\) & "
        "\\(e_K^{\\rm s}\\) (\\%) & \\(e_\\phi\\) (\\%) & \\(e_u\\) (\\%) & \\(e_p\\) (\\%) \\\\",
        "\\midrule",
    ]
    for case, block in df.groupby("case", sort=False):
        for _, row in block.iterrows():
            degenerate = case == "orthogonal_duct"
            lines.append(
                "%s & %s & %d & %d & %s & %s & %s & %s & %s & %s \\\\" % (
                    CASE_DISPLAY.get(case, case), row["level_label"].split("_")[0],
                    int(row["N_cv"]), int(row["N_system"]),
                    fmt(row["h_S_over_h"], 0), fmt(row["q_S_over_h"], 1),
                    (fmt(row["e_K_signed_percent"], 2) + (r"\(^{\dagger}\)" if case == "bentheimer_crop" and int(row["N_cv"]) in (400, 3200) else "")), fmt(row["e_phi_percent"], 2),
                    fmt(row["e_u_percent"], 2),
                    "--" if degenerate else fmt(row["e_p_percent"], 2),
                )
            )
        lines.append("\\midrule")
    lines[-1] = "\\bottomrule"
    lines += ["\\end{tabular}"]
    if any("resizebox" in line for line in lines):
        lines.append("}")
    lines += ["\\endgroup", "\\end{table}"]
    (GEN / "controlled_refinement_table.tex").write_text(
        HEADER % path.relative_to(PROJECT).as_posix() + "\n".join(lines) + "\n", encoding="utf-8"
    )

    slopes = {}
    for case, block in df.groupby("case", sort=False):
        block = block.sort_values("level_index")
        entry = {}
        for metric in ["e_K_percent", "e_phi_percent", "e_u_percent", "e_p_percent"]:
            values = block[metric].values
            if not np.all(np.isfinite(values)) or np.any(values <= 0):
                continue
            for name, count in (("all_levels", None), ("last_three", 3)):
                a, r2 = slope(block["N_cv"].values ** (1.0 / 3.0), values, count)
                entry["%s__vs_mean_cell_size__%s" % (metric, name)] = {
                    "slope": -a, "r_squared": r2
                }
        entry["levels"] = block["level_label"].tolist()
        entry["h_S_over_h"] = block["h_S_over_h"].tolist()
        entry["q_S_over_h"] = block["q_S_over_h"].tolist()
        entry["e_u_percent"] = block["e_u_percent"].tolist()
        entry["e_phi_percent"] = block["e_phi_percent"].tolist()
        entry["e_K_percent"] = block["e_K_percent"].tolist()
        entry["e_K_signed_percent"] = block["e_K_signed_percent"].tolist()
        entry["e_p_percent"] = block["e_p_percent"].tolist()
        entry["N_cv"] = block["N_cv"].tolist()
        entry["N_system"] = block["N_system"].tolist()
        slopes[case] = entry
    summary["controlled_refinement"] = slopes
    return df


