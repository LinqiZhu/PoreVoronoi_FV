def cost_scaling_law(summary):
    """Reducing cells does not reduce work, and the exponents say why.

    The unknowns of this formulation live on the interface facelets, not on the
    cells.  Total interfacial area of a partition into N_c cells of a fixed
    domain grows as N_c^{1/3}, so the unknown count follows that law rather than
    N_c.  The nonzero count runs the other way: coarsening puts more trace modes
    on each cell, the local block grows as the square of that number, and the
    product beats the reduction in cell count.  Both exponents are fitted here on
    each family so the statement is a measurement rather than a scaling argument.
    """
    path = REV / "supplementary/s4_cost" / "cost_and_sizes.csv"
    if not path.exists():
        return None
    df = pd.read_csv(path)
    needed = {"case", "N_cv", "N_interface_facelets", "N_system", "nnz_KKT"}
    if not needed.issubset(df.columns):
        return None
    order = {"orthogonal_duct": 0, "skewed_duct": 1, "bentheimer_crop": 2}

    def exponent(x, y):
        lx, ly = np.log(np.asarray(x, float)), np.log(np.asarray(y, float))
        slope, _ = np.polyfit(lx, ly, 1)
        return float(slope), float(np.corrcoef(lx, ly)[0, 1])

    lines = [
        "\\begin{table}[t]", "\\centering",
        "\\caption{Why coarsening does not reduce the work. Fitted power laws in "
        "the control-volume count along each controlled refinement family. The "
        "unknowns sit on interface facelets, whose total number follows the "
        "surface-to-volume law \\(N_c^{1/3}\\); the nonzero count carries the "
        "opposite sign, because a coarser cell carries more trace modes and its "
        "local block grows as the square of that number. \\(R\\) is the "
        "correlation of the fit in log--log.}",
        "\\label{tab:cost-scaling-law}", "\\begingroup", "\\scriptsize",
        "\\begin{tabular}{@{}lrrrrrr@{}}", "\\toprule",
        " & \\multicolumn{2}{c}{\\(N_{\\rm fl}\\)} & "
        "\\multicolumn{2}{c}{\\(N_{\\rm sys}\\)} & "
        "\\multicolumn{2}{c}{\\(\\mathrm{nnz}\\)} \\\\",
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}",
        "Case & exponent & \\(R\\) & exponent & \\(R\\) & exponent & \\(R\\) \\\\",
        "\\midrule",
    ]
    record = {"surface_law_exponent": 1.0 / 3.0}
    for case in sorted(set(df["case"]), key=lambda c: order.get(c, 9)):
        block = df[df["case"] == case].sort_values("N_cv")
        if len(block) < 4:
            continue
        entry = {}
        cells = block["N_cv"]
        for key, column in (("facelets", "N_interface_facelets"),
                            ("system", "N_system"), ("nnz", "nnz_KKT")):
            slope, correlation = exponent(cells, block[column])
            entry[key + "_exponent"] = slope
            entry[key + "_correlation"] = correlation
        entry["nnz_per_row_coarsest"] = float(
            block["nnz_KKT"].iloc[0] / block["N_system"].iloc[0])
        entry["nnz_per_row_finest"] = float(
            block["nnz_KKT"].iloc[-1] / block["N_system"].iloc[-1])
        entry["nnz_coarsest_over_finest"] = float(
            block["nnz_KKT"].iloc[0] / block["nnz_KKT"].iloc[-1])
        entry["cells_ratio"] = float(block["N_cv"].iloc[-1] / block["N_cv"].iloc[0])
        entry["system_ratio"] = float(block["N_system"].iloc[-1] / block["N_system"].iloc[0])
        record[case] = entry
        lines.append("%s & %s & %s & %s & %s & %s & %s \\\\" % (
            CASE_DISPLAY.get(case, case),
            fmt(entry["facelets_exponent"], 3), fmt(entry["facelets_correlation"], 4),
            fmt(entry["system_exponent"], 3), fmt(entry["system_correlation"], 4),
            fmt(entry["nnz_exponent"], 3), fmt(entry["nnz_correlation"], 4),
        ))
    lines += ["\\bottomrule", "\\end{tabular}", "\\endgroup", "\\end{table}"]
    (GEN / "cost_scaling_law_table.tex").write_text(
        HEADER % path.relative_to(PROJECT).as_posix() + "\n".join(lines) + "\n", encoding="utf-8"
    )
    families = [record[c] for c in order if c in record]
    if families:
        record["facelet_exponent_min"] = min(f["facelets_exponent"] for f in families)
        record["facelet_exponent_max"] = max(f["facelets_exponent"] for f in families)
        record["nnz_exponent_min"] = min(f["nnz_exponent"] for f in families)
        record["nnz_exponent_max"] = max(f["nnz_exponent"] for f in families)
        record["families_with_negative_nnz_exponent"] = int(sum(
            1 for f in families if f["nnz_exponent"] < 0.0))
        record["families"] = len(families)
    summary["cost_scaling_law"] = record
    return record


